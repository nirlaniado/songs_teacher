import { useRef, useState } from "react";
import { SLIDE_H, SLIDE_W, type ShapeKind } from "../../schema/deck.js";
import { TUNING_PRESETS, tabScaffold } from "../../deck/templates.js";
import { centeredFrame, useDeckStore } from "../../store/deckStore.js";
import { Button, Field } from "../controls.js";

/**
 * Insert bar + arrange/align + view controls + undo/redo + save + present.
 *
 * Laid out in Impress's order — insert, then arrange, then view — because the
 * whole point of mirroring its arrangement is that someone who knows Impress
 * finds things where they expect them.
 */

/** The zoom steps Impress offers, plus "fit" which tracks the window. */
const ZOOM_STEPS = [0.25, 0.5, 0.75, 1, 1.5, 2];

const SHAPES: Array<{ shape: ShapeKind; label: string }> = [
  { shape: "rect", label: "Rectangle" },
  { shape: "roundRect", label: "Rounded rectangle" },
  { shape: "ellipse", label: "Ellipse" },
  { shape: "line", label: "Line" },
  { shape: "arrow", label: "Arrow" },
];

const ALIGNMENTS: Array<{ mode: "left" | "center" | "right" | "top" | "middle" | "bottom"; glyph: string; label: string }> = [
  { mode: "left", glyph: "⬅", label: "Align left" },
  { mode: "center", glyph: "↔", label: "Centre horizontally" },
  { mode: "right", glyph: "➡", label: "Align right" },
  { mode: "top", glyph: "⬆", label: "Align top" },
  { mode: "middle", glyph: "↕", label: "Centre vertically" },
  { mode: "bottom", glyph: "⬇", label: "Align bottom" },
];

/**
 * A newly inserted shape.
 *
 * Lines and arrows get a wide, thin frame with a visible stroke and no fill —
 * inserting one as a 320x200 filled box (the default for a closed shape) reads
 * as a bug, not a line.
 */
function newShape(shape: ShapeKind) {
  if (shape === "line" || shape === "arrow") {
    return {
      kind: "shape" as const,
      x: 160,
      y: SLIDE_H / 2,
      w: SLIDE_W - 320,
      h: 24,
      rotation: 0,
      locked: false,
      shape,
      strokeWidth: 4,
    };
  }
  return { kind: "shape" as const, ...centeredFrame(320, 200), shape, strokeWidth: 0 };
}

export function EditorToolbar({ onPresent }: { onPresent: () => void }) {
  const deck = useDeckStore((s) => s.deck);
  const addElement = useDeckStore((s) => s.addElement);
  const undo = useDeckStore((s) => s.undo);
  const redo = useDeckStore((s) => s.redo);
  const canUndo = useDeckStore((s) => s.past.length > 0);
  const canRedo = useDeckStore((s) => s.future.length > 0);
  const saveDeck = useDeckStore((s) => s.saveDeck);
  const saving = useDeckStore((s) => s.saving);
  const dirty = useDeckStore((s) => s.isDirty());
  const uploadImage = useDeckStore((s) => s.uploadImage);
  const setTitle = useDeckStore((s) => s.setTitle);

  const selectionCount = useDeckStore((s) => s.selectedElementIds.length);
  const arrangeSelection = useDeckStore((s) => s.arrangeSelection);
  const alignSelection = useDeckStore((s) => s.alignSelection);
  const distributeSelection = useDeckStore((s) => s.distributeSelection);
  const duplicateSelection = useDeckStore((s) => s.duplicateSelection);

  const zoom = useDeckStore((s) => s.zoom);
  const setZoom = useDeckStore((s) => s.setZoom);
  const showGrid = useDeckStore((s) => s.showGrid);
  const toggleGrid = useDeckStore((s) => s.toggleGrid);
  const snapEnabled = useDeckStore((s) => s.snapEnabled);
  const toggleSnap = useDeckStore((s) => s.toggleSnap);

  const exportDeck = useDeckStore((s) => s.exportDeck);
  const hasStems = useDeckStore((s) => (s.deck?.audio?.stems?.length ?? 0) > 0);

  const imageInput = useRef<HTMLInputElement>(null);
  const [exporting, setExporting] = useState(false);
  const [shapeMenu, setShapeMenu] = useState(false);
  const [tuningMenu, setTuningMenu] = useState(false);

  function insertTab(tuningId: string) {
    const tuning = TUNING_PRESETS.find((t) => t.id === tuningId) ?? TUNING_PRESETS[0]!;
    addElement({
      kind: "tab",
      ...centeredFrame(560, 200),
      text: tabScaffold(tuning),
      style: { fontSize: 20, valign: "top", lineHeight: 1.3 },
    });
  }

  const hasSelection = selectionCount > 0;

  async function download() {
    // Stems are hundreds of megabytes and can be regenerated by separating
    // again, so they're left out unless explicitly asked for.
    const includeStems = hasStems && window.confirm(
      "Include the separated stems?\n\n" +
        "OK — bundle everything (much larger file).\n" +
        "Cancel — deck, audio and images only; stems can be re-created by separating again.",
    );
    setExporting(true);
    try {
      await exportDeck({ includeStems });
    } finally {
      setExporting(false);
    }
  }

  async function insertImage(file: File) {
    const path = await uploadImage(file);
    if (!path) return;
    addElement({
      kind: "image",
      ...centeredFrame(560, 360),
      src: path,
      fit: "contain",
    });
  }

  return (
    <div className="flex flex-wrap items-center gap-0.5 border-b border-line bg-panel px-3 py-1.5">
      <Field
        value={deck?.title ?? ""}
        onChange={(e) => setTitle(e.target.value)}
        className="mr-1 w-44 border-transparent bg-transparent font-medium hover:border-line"
        placeholder="Untitled presentation"
        aria-label="Presentation title"
      />

      <span className="mx-1 h-4 w-px bg-line" />

      <Button variant="subtle"
        onClick={() =>
          addElement({
            kind: "text",
            ...centeredFrame(600, 120),
            text: "",
            role: "none",
            style: {
              fontSize: 32,
              bold: false,
              italic: false,
              underline: false,
              align: "left",
              valign: "top",
              lineHeight: 1.25,
            },
          })
        }
      >
        + Text
      </Button>
      <Button variant="subtle" onClick={() => imageInput.current?.click()}>
        + Image
      </Button>
      {/* Tuning picker — same dropdown pattern as shapes below. Picking one
          inserts a labelled, dash-filled scaffold in that tuning; "Standard"
          is first so a plain click-through gives the common case. */}
      <div className="relative">
        <Button variant="subtle"
          title="Guitar/bass tab — starts as a blank six-string scaffold, extend and edit freely"
          aria-haspopup="menu"
          aria-expanded={tuningMenu}
          onClick={() => setTuningMenu((v) => !v)}
        >
          + Tab ▾
        </Button>
        {tuningMenu && (
          <div
            className="pop absolute left-0 top-full z-40 mt-1 w-56 rounded-surface border border-line bg-panel p-1 shadow-xl"
            onMouseLeave={() => setTuningMenu(false)}
          >
            {TUNING_PRESETS.map(({ id, label }) => (
              <button
                key={id}
                onClick={() => {
                  setTuningMenu(false);
                  insertTab(id);
                }} className="menu-item"
              >
                {label}
              </button>
            ))}
          </div>
        )}
      </div>
      <input
        ref={imageInput}
        type="file"
        accept="image/*"
        hidden
        onChange={(e) => {
          const f = e.target.files?.[0];
          if (f) void insertImage(f);
          e.target.value = "";
        }}
      />
      {/* Shape picker — Impress puts its shapes behind one dropdown too. */}
      <div className="relative">
        <Button variant="subtle" aria-haspopup="menu" aria-expanded={shapeMenu} onClick={() => setShapeMenu((v) => !v)}>
          + Shape ▾
        </Button>
        {shapeMenu && (
          <div
            className="pop absolute left-0 top-full z-40 mt-1 w-40 rounded-surface border border-line bg-panel p-1 shadow-xl"
            onMouseLeave={() => setShapeMenu(false)}
          >
            {SHAPES.map(({ shape, label }) => (
              <button
                key={shape}
                onClick={() => {
                  setShapeMenu(false);
                  addElement(newShape(shape));
                }} className="menu-item"
              >
                {label}
              </button>
            ))}
          </div>
        )}
      </div>

      <span className="mx-1 h-4 w-px bg-line" />

      {/* Arrange — Impress's Shape ▸ Arrange, on the selection. */}
      <Button variant="subtle" icon
        disabled={!hasSelection}
        onClick={() => arrangeSelection("front")}
        title="Bring to front (Ctrl+Shift+Home)"
        aria-label="Bring to front"
      >
        ⤒
      </Button>
      <Button variant="subtle" icon
        disabled={!hasSelection}
        onClick={() => arrangeSelection("forward")}
        title="Bring forward (Ctrl+Shift+↑)"
        aria-label="Bring forward"
      >
        ↑
      </Button>
      <Button variant="subtle" icon
        disabled={!hasSelection}
        onClick={() => arrangeSelection("backward")}
        title="Send backward (Ctrl+Shift+↓)"
        aria-label="Send backward"
      >
        ↓
      </Button>
      <Button variant="subtle" icon
        disabled={!hasSelection}
        onClick={() => arrangeSelection("back")}
        title="Send to back (Ctrl+Shift+End)"
        aria-label="Send to back"
      >
        ⤓
      </Button>

      <span className="mx-1 h-4 w-px bg-line" />

      {/* Align. One element aligns to the slide, several to each other. */}
      {ALIGNMENTS.map(({ mode, glyph, label }) => (
        <Button variant="subtle" icon
          key={mode}
          disabled={!hasSelection}
          onClick={() => alignSelection(mode)}
          title={selectionCount > 1 ? `${label} (within the selection)` : `${label} (on the slide)`}
          aria-label={label}
        >
          {glyph}
        </Button>
      ))}
      <Button variant="subtle" icon
        disabled={selectionCount < 3}
        onClick={() => distributeSelection("horizontal")}
        title="Distribute horizontally — needs three or more"
        aria-label="Distribute horizontally"
      >
        ⇹
      </Button>
      <Button variant="subtle" icon
        disabled={selectionCount < 3}
        onClick={() => distributeSelection("vertical")}
        title="Distribute vertically — needs three or more"
        aria-label="Distribute vertically"
      >
        ⇳
      </Button>
      <Button variant="subtle" icon
        disabled={!hasSelection}
        onClick={duplicateSelection}
        title="Duplicate (Ctrl+D)"
        aria-label="Duplicate"
      >
        ⧉
      </Button>

      <span className="mx-1 h-4 w-px bg-line" />

      {/* View — grid, snapping and zoom. */}
      <Button variant="subtle" icon pressed={showGrid}
        onClick={toggleGrid}
        title="Show grid"
        aria-label="Show grid"
      >
        ▦
      </Button>
      <Button variant="subtle" icon pressed={snapEnabled}
        onClick={toggleSnap}
        title="Snap to guides — hold Alt while dragging to suspend"
        aria-label="Snap to guides"
      >
        🧲
      </Button>
      <Field
        as="select"
        className="w-[4.25rem]"
        value={zoom === "fit" ? "fit" : String(zoom)}
        onChange={(e) => setZoom(e.target.value === "fit" ? "fit" : Number(e.target.value))}
        title="Zoom"
        aria-label="Zoom"
      >
        <option value="fit">Fit</option>
        {ZOOM_STEPS.map((step) => (
          <option key={step} value={step}>
            {Math.round(step * 100)}%
          </option>
        ))}
      </Field>

      <span className="mx-1 h-4 w-px bg-line" />

      <Button variant="subtle" icon onClick={undo} disabled={!canUndo} title="Undo (Ctrl+Z)" aria-label="Undo">
        ↶
      </Button>
      <Button variant="subtle" icon onClick={redo} disabled={!canRedo} title="Redo (Ctrl+Shift+Z)" aria-label="Redo">
        ↷
      </Button>

      <div className="ml-auto flex items-center gap-2">
        {dirty && <span className="text-[11px] text-warning">Unsaved</span>}
        <Button
          onClick={() => void saveDeck()}
          disabled={!dirty || saving}
        >
          {saving ? "Saving…" : "Save"}
        </Button>
        <Button
          onClick={() => void download()}
          disabled={!deck || exporting}
          title={
            hasStems
              ? "Download as a .zip — you'll be asked whether to include the stems"
              : "Download the presentation and its media as a .zip"
          }
        >
          {exporting ? "Packing…" : "⭳ Download"}
        </Button>
        <Button variant="primary"
          onClick={onPresent}
          disabled={!deck || deck.slides.length === 0}
        >
          ▶ Present
        </Button>
      </div>
    </div>
  );
}
